-- Secure administrator profiles, role management and account lifecycle.
-- Super Admin accounts are visible for accountability but cannot be changed
-- through the administrator-management interface.

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  target_user_id uuid,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.admin_audit_log enable row level security;
revoke all on public.admin_audit_log from anon, authenticated;
grant select, insert on public.admin_audit_log to authenticated;

drop policy if exists "admin_audit_super_admin_select" on public.admin_audit_log;
create policy "admin_audit_super_admin_select"
on public.admin_audit_log for select
to authenticated
using (private.has_role('super_admin'));

drop policy if exists "admin_audit_super_admin_insert" on public.admin_audit_log;
create policy "admin_audit_super_admin_insert"
on public.admin_audit_log for insert
to authenticated
with check (
  private.has_role('super_admin')
  and actor_user_id = (select auth.uid())
);

create or replace function private.is_active_account(account_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = account_id
      and is_active
  );
$$;

revoke all on function private.is_active_account(uuid) from public;
grant execute on function private.is_active_account(uuid) to authenticated;

create or replace function private.has_role(required_role public.app_role)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_roles ur
    join public.profiles p on p.id = ur.user_id and p.is_active
    where ur.user_id = (select auth.uid())
      and ur.role = required_role
  );
$$;

drop policy if exists "roles_select_own_or_admin" on public.user_roles;
create policy "roles_select_own_or_admin"
on public.user_roles for select
to authenticated
using (
  (
    user_id = (select auth.uid())
    and private.is_active_account((select auth.uid()))
  )
  or private.has_role('super_admin')
);

-- All role mutations now go through guarded RPCs. This closes the direct table
-- path that previously allowed a Super Admin session to create or modify
-- another Super Admin account.
drop policy if exists "roles_super_admin_insert" on public.user_roles;
drop policy if exists "roles_super_admin_update" on public.user_roles;
drop policy if exists "roles_super_admin_delete" on public.user_roles;
revoke insert, update, delete on public.user_roles from authenticated;

drop function if exists public.admin_user_directory();
create function public.admin_user_directory()
returns table (
  user_id uuid,
  email text,
  full_name text,
  phone text,
  is_active boolean,
  roles text[],
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.has_role('super_admin') then
    raise exception 'Super Admin access is required.';
  end if;

  return query
  select
    p.id,
    coalesce(p.email, ''),
    p.full_name,
    coalesce(p.phone, ''),
    p.is_active,
    coalesce(
      array_agg(ur.role::text order by ur.role::text) filter (where ur.role is not null),
      array[]::text[]
    ),
    p.created_at
  from public.profiles p
  join public.user_roles ur on ur.user_id = p.id
  where exists (
    select 1
    from public.user_roles admin_role
    where admin_role.user_id = p.id
      and admin_role.role in (
        'super_admin',
        'product_inventory_manager',
        'order_delivery_manager',
        'customer_support',
        'finance_manager',
        'content_promotion_manager'
      )
  )
  group by p.id, p.email, p.full_name, p.phone, p.is_active, p.created_at
  order by
    case when exists (
      select 1 from public.user_roles protected_role
      where protected_role.user_id = p.id and protected_role.role = 'super_admin'
    ) then 0 else 1 end,
    lower(coalesce(p.full_name, p.email, ''));
end;
$$;

revoke all on function public.admin_user_directory() from public;
grant execute on function public.admin_user_directory() to authenticated;

create or replace function public.update_admin_account(
  target_user_id uuid,
  requested_full_name text,
  requested_phone text,
  requested_is_active boolean,
  requested_roles text[]
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  allowed_roles constant text[] := array[
    'product_inventory_manager',
    'order_delivery_manager',
    'customer_support',
    'finance_manager',
    'content_promotion_manager'
  ];
  requested_role text;
begin
  if not private.has_role('super_admin') then
    raise exception 'Super Admin access is required.';
  end if;
  if target_user_id = (select auth.uid()) or exists (
    select 1 from public.user_roles
    where user_id = target_user_id and role = 'super_admin'
  ) then
    raise exception 'Super Admin accounts are protected and cannot be changed here.';
  end if;
  if not exists (
    select 1 from public.user_roles
    where user_id = target_user_id and role::text = any(allowed_roles)
  ) then
    raise exception 'The selected administrator does not exist.';
  end if;
  if nullif(trim(requested_full_name), '') is null then
    raise exception 'The administrator name is required.';
  end if;
  if coalesce(array_length(requested_roles, 1), 0) = 0 then
    raise exception 'Select at least one administration role.';
  end if;
  if exists (
    select 1 from unnest(requested_roles) role_name
    where not (role_name = any(allowed_roles))
  ) then
    raise exception 'One or more requested roles cannot be assigned.';
  end if;

  update public.profiles
  set full_name = trim(requested_full_name),
      phone = nullif(trim(coalesce(requested_phone, '')), ''),
      account_type = 'team_member',
      is_active = requested_is_active,
      updated_at = now()
  where id = target_user_id;

  delete from public.user_roles
  where user_id = target_user_id
    and role::text = any(allowed_roles);

  foreach requested_role in array requested_roles
  loop
    insert into public.user_roles (user_id, role, assigned_by)
    values (target_user_id, requested_role::public.app_role, (select auth.uid()))
    on conflict (user_id, role) do update
      set assigned_by = excluded.assigned_by,
          assigned_at = now();
  end loop;

  insert into public.admin_audit_log (actor_user_id, target_user_id, action, details)
  values (
    (select auth.uid()),
    target_user_id,
    'admin_account_updated',
    jsonb_build_object(
      'full_name', trim(requested_full_name),
      'phone', nullif(trim(coalesce(requested_phone, '')), ''),
      'is_active', requested_is_active,
      'roles', requested_roles
    )
  );
end;
$$;

revoke all on function public.update_admin_account(uuid, text, text, boolean, text[]) from public;
grant execute on function public.update_admin_account(uuid, text, text, boolean, text[]) to authenticated;

