-- Fail before changing the schema if the expected original application setup is
-- incomplete. The existing admin_invitations table was confirmed by the live API.
do $activation_preflight$
declare
  requirement record;
  required_column text;
  required_role text;
  required_function text;
begin
  for requirement in
    select * from (values
      ('auth.users', array['id','email','email_confirmed_at','created_at']::text[]),
      ('public.profiles', array['id','email','full_name','phone','account_type','is_active','created_at','updated_at']::text[]),
      ('public.user_roles', array['user_id','role','assigned_by','assigned_at']::text[]),
      ('public.admin_invitations', array['id','email','full_name','phone','roles','status','invited_by','accepted_by','expires_at','accepted_at','created_at','updated_at']::text[]),
      ('storage.buckets', array['id','name','public','file_size_limit','allowed_mime_types']::text[]),
      ('storage.objects', array['bucket_id','name']::text[])
    ) as prerequisites(relation_name, required_columns)
  loop
    if to_regclass(requirement.relation_name) is null then
      raise exception 'Admin activation prerequisite missing: %', requirement.relation_name;
    end if;
    foreach required_column in array requirement.required_columns loop
      if not exists (
        select 1 from pg_attribute
        where attrelid = to_regclass(requirement.relation_name)
          and attname = required_column and attnum > 0 and not attisdropped
      ) then
        raise exception 'Admin activation prerequisite column missing: %.%', requirement.relation_name, required_column;
      end if;
    end loop;
  end loop;

  foreach required_function in array array[
    'auth.uid()', 'auth.jwt()', 'public.set_updated_at()',
    'private.has_role(public.app_role)', 'storage.foldername(text)'
  ] loop
    if to_regprocedure(required_function) is null then
      raise exception 'Admin activation prerequisite function missing: %', required_function;
    end if;
  end loop;

  foreach required_role in array array['anon','authenticated','service_role'] loop
    if not exists (select 1 from pg_roles where rolname = required_role) then
      raise exception 'Admin activation prerequisite database role missing: %', required_role;
    end if;
  end loop;

  foreach required_role in array array[
    'super_admin','product_inventory_manager','order_delivery_manager',
    'customer_support','finance_manager','content_promotion_manager'
  ] loop
    if not exists (
      select 1 from pg_enum
      where enumtypid = to_regtype('public.app_role') and enumlabel = required_role
    ) then
      raise exception 'Admin activation prerequisite app_role value missing: %', required_role;
    end if;
  end loop;

  if to_regclass('public.admin_profiles') is null then
    if not exists (
      select 1 from public.user_roles r
      join public.profiles p on p.id = r.user_id and p.is_active
      join auth.users u on u.id = r.user_id
      where r.role::text = 'super_admin'
    ) then
      raise exception 'Admin activation requires an existing active Super Admin before the one-time profile seed.';
    end if;
  else
    -- On rerun, use the existing independent Admin status. A deactivated
    -- customer profile must not prevent an active Admin from keeping access.
    if not exists (
      select 1 from public.user_roles r
      join public.admin_profiles p on p.user_id = r.user_id and p.is_active
      join auth.users u on u.id = r.user_id
      where r.role::text = 'super_admin'
    ) then
      raise exception 'Admin activation requires an existing active Super Admin profile.';
    end if;
  end if;
end;
$activation_preflight$;

