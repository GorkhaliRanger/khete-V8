create function public.admin_user_directory()
returns table (
  user_id uuid,
  email text,
  full_name text,
  phone text,
  is_active boolean,
  roles text[],
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.has_role('super_admin') then
    raise exception 'Super Admin access is required.';
  end if;

  return query
  select
    p.id,
    coalesce(p.email, ''),
    p.full_name,
    coalesce(p.phone, ''),
    p.is_active,
    coalesce(
      array_agg(ur.role::text order by ur.role::text) filter (where ur.role is not null),
      array[]::text[]
    ),
    p.created_at
  from public.profiles p
  join public.user_roles ur on ur.user_id = p.id
  where exists (
    select 1
    from public.user_roles admin_role
    where admin_role.user_id = p.id
      and admin_role.role in (
        'super_admin',
        'product_inventory_manager',
        'order_delivery_manager',
        'customer_support',
        'finance_manager',
        'content_promotion_manager'
      )
  )
  group by p.id, p.email, p.full_name, p.phone, p.is_active, p.created_at
  order by
    case when exists (
      select 1 from public.user_roles protected_role
      where protected_role.user_id = p.id and protected_role.role = 'super_admin'
    ) then 0 else 1 end,
    lower(coalesce(p.full_name, p.email, ''));
end;
$$;

